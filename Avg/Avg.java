        public static double[] runsAvg(int[][] runs) {

                double avgs[] = new double[runs[0].length];
                double dnm = runs.length;

                for (int j = 0; j < runs[0].length; j++) {

                        double sum = 0.0;

                        for (int i = 0; i < runs.length; i++) {

                                sum += runs[i][j];

                        }

                        avgs[j] = sum / dnm;

                }

                return avgs;

        }

